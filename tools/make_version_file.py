"""按 ``mcrender/__init__.py`` 的 ``__version__`` 生成 PyInstaller 的**版本资源文件**。

    python tools/make_version_file.py [输出路径] [--exe 原始文件名]

默认写 ``build/version_info.txt``。``build_exe.bat`` 在打包前调用它，把结果交给
``--version-file`` —— 于是 exe 的「属性 → 详细信息」里显示的版本号跟窗口标题、
标题旁的色块**是同一串**。版本号仍然只有 ``mcrender/__init__.py`` 一处，别在这里写死。

为什么单独一个脚本、而不是把 ``VSVersionInfo(...)`` 手写进仓库：那份文件里的版本号会
和 ``__version__`` 各改各的，早晚对不上。这里现读现生成，改版本号只动一个地方。

只依赖标准库（用 ``ast`` 读常量，**不 import 那个包**）—— 打包用的解释器不一定装齐
GUI 依赖（customtkinter / Pillow），这个脚本得能在任何 Python 3.8+ 上跑。

⚠️ 版本资源里的字符串一律用 **ASCII**：这个文件是交给 PyInstaller 的 ``eval`` 解析的，
带中文要多操一份编码的心，没必要。
"""
from __future__ import annotations

import argparse
import ast
import os
import re
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
INIT = os.path.join(ROOT, "mcrender", "__init__.py")

PRODUCT = "Bedrock Recipe Renderer X"
COMPANY = "NewBee"
COPYRIGHT = "Copyright (c) 2026 NewBee. MIT License."

TEMPLATE = """\
# Generated by tools/make_version_file.py -- do not edit by hand.
# Source of truth: mcrender/__init__.py::__version__ = {version!r}
VSVersionInfo(
  ffi=FixedFileInfo(
    filevers={vers},
    prodvers={vers},
    mask=0x3f,
    flags=0x0,
    OS=0x40004,
    fileType=0x1,
    subtype=0x0,
    date=(0, 0)
  ),
  kids=[
    StringFileInfo([
      StringTable(
        '080404B0',
        [StringStruct('CompanyName', '{company}'),
         StringStruct('FileDescription', '{description}'),
         StringStruct('FileVersion', '{version}'),
         StringStruct('InternalName', '{internal}'),
         StringStruct('LegalCopyright', '{copyright}'),
         StringStruct('OriginalFilename', '{exe}'),
         StringStruct('ProductName', '{product}'),
         StringStruct('ProductVersion', '{version}')])
    ]),
    VarFileInfo([VarStruct('Translation', [2052, 1200])])
  ]
)
"""


def read_version(path: str = INIT) -> str:
    """从包的 ``__init__.py`` 里读出 ``__version__``（只解析，不执行）。"""
    with open(path, encoding="utf-8") as fh:
        tree = ast.parse(fh.read(), path)
    for node in tree.body:
        if not isinstance(node, ast.Assign):
            continue
        for target in node.targets:
            if isinstance(target, ast.Name) and target.id == "__version__":
                return str(ast.literal_eval(node.value))
    raise SystemExit(f"{path} 里找不到 __version__")


def version_quad(text: str) -> tuple:
    """``"1.1.0"`` → ``(1, 1, 0, 0)``：资源里要的是 4 段整数（不足补 0）。"""
    head = re.split(r"[-+]", text, maxsplit=1)[0]          # 去掉 -rc1 / +build 这类后缀
    parts = [int(n) for n in re.findall(r"\d+", head)][:4]
    return tuple((parts + [0, 0, 0, 0])[:4])


def render(version: str, exe: str, description: str) -> str:
    quad = version_quad(version)
    return TEMPLATE.format(
        version=version,
        vers="(" + ", ".join(str(n) for n in quad) + ")",
        company=COMPANY,
        description=description,
        internal=os.path.splitext(exe)[0],
        copyright=COPYRIGHT,
        exe=exe,
        product=PRODUCT,
    )


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description="生成 exe 的版本资源文件")
    parser.add_argument("out", nargs="?", default=os.path.join(ROOT, "build", "version_info.txt"))
    parser.add_argument("--exe", default="bedrock-recipe-renderer.exe",
                        help="OriginalFilename（默认 GUI 那个 exe）")
    parser.add_argument("--description", default=None,
                        help="FileDescription（默认：ProductName + 「 (CLI)」按 exe 名判断）")
    args = parser.parse_args(argv)

    version = read_version()
    description = args.description
    if description is None:
        description = PRODUCT + (" (CLI)" if "cli" in args.exe.lower() else "")
    text = render(version, args.exe, description)

    folder = os.path.dirname(os.path.abspath(args.out))
    if folder:
        os.makedirs(folder, exist_ok=True)
    with open(args.out, "w", encoding="utf-8", newline="\n") as fh:
        fh.write(text)

    quad = version_quad(version)
    print(f"版本 {version}（{quad[0]}.{quad[1]}.{quad[2]}.{quad[3]}）"
          f" → {args.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
